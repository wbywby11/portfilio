/** 首次进入时为每张表生成样例数据：优先使用 REALISTIC_SEEDS，未覆盖的表回退到 schema 自动生成 5 条 */
export function seedIfNeeded() {
  // 清理旧版本的 localStorage 数据
  for (let i = 1; i < SEED_VERSION; i++) {
    localStorage.removeItem(`zy_data_domain_mock_seeded_v${i}`);
    localStorage.removeItem(`zy_data_domain_mock_v${i}`);
  }

  loadStore();
  if (localStorage.getItem(SEEDED_KEY) === '1') return;

  // 1. 优先使用 REALISTIC_SEEDS 中的预定义真实数据
  Object.keys(REALISTIC_SEEDS).forEach(collection => {
    const seeds = REALISTIC_SEEDS[collection];
    store[collection] = seeds.map((row, idx) => ({
      _id: `m_${collection}_${String(idx + 1).padStart(4, '0')}`,
      ...row,
      etl_dt: KEYS.BIZ_DT,
      src_sys: 'MOCK',
    }));
  });

  // 2. 对于 REALISTIC_SEEDS 未覆盖的表，回退到原有 schema-based 自动生成
  DOMAINS.forEach(domain => {
    domain.tables.forEach(table => {
      if (REALISTIC_SEEDS[table.name]) return; // 已使用真实种子，跳过
      if (!store[table.name] || store[table.name].length === 0) {
        const rows = [];
        for (let i = 0; i < 5; i++) rows.push(genRecord(table, i));
        store[table.name] = rows;
      }
    });
  });

  saveStore();
  localStorage.setItem(SEEDED_KEY, '1');
}

/** 重新种子（清空所有 mock 数据并重建） */
export function reseed() {
  store = {};
  saveStore();
  localStorage.removeItem(SEEDED_KEY);
  seedIfNeeded();
}

function applyFilter(rows, filters) {
  if (!filters) return rows;
  return rows.filter(r => {
    for (const k in filters) {
      const v = filters[k];
      if (v === '' || v === null || v === undefined) continue;
      const rv = r[k];
      if (rv === null || rv === undefined) return false;
      if (String(rv).toLowerCase().indexOf(String(v).toLowerCase()) === -1) return false;
    }
    return true;
  });
}

/** ============ CRUD API（与后端接口契约一致） ============ */

export function list(collection, params = {}) {
  loadStore();
  const all = store[collection] || [];
  const filtered = applyFilter(all, params.filters);
  const page = parseInt(params.page || 1, 10);
  const pageSize = parseInt(params.pageSize || 20, 10);
  const start = (page - 1) * pageSize;
  return Promise.resolve({
    records: filtered.slice(start, start + pageSize),
    total: filtered.length,
    page,
    pageSize,
    _mock: true
  });
}

export function create(collection, payload) {
  loadStore();
  if (!store[collection]) store[collection] = [];
  const rec = { _id: uid(), ...payload, etl_dt: KEYS.BIZ_DT, src_sys: 'MOCK' };
  store[collection].push(rec);
  saveStore();
  return Promise.resolve(rec);
}

export function update(collection, id, payload) {
  loadStore();
  const list = store[collection] || [];
  const idx = list.findIndex(r => r._id === id);
  if (idx < 0) return Promise.reject(new Error('not found'));
  list[idx] = { ...list[idx], ...payload, etl_dt: KEYS.BIZ_DT };
  saveStore();
  return Promise.resolve(list[idx]);
}

export function remove(collection, id) {
  loadStore();
  const list = store[collection] || [];
  const idx = list.findIndex(r => r._id === id);
  if (idx < 0) return Promise.reject(new Error('not found'));
  list.splice(idx, 1);
  saveStore();
  return Promise.resolve({ ok: true });
}

export function count(collection) {
  loadStore();
  return Promise.resolve({ count: (store[collection] || []).length });
}

export default { seedIfNeeded, reseed, list, create, update, remove, count };
