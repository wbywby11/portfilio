def build_synonym_index() -> dict[str, set[str]]:
    """构建 word -> synonym_group 快速索引
    
    Returns:
        字典，key 为词语，value 为该词所属的同义词组
    """
    index: dict[str, set[str]] = {}
    for group in SYNONYM_GROUPS:
        for word in group:
            # 每个词映射到其所在的完整组
            index[word.lower()] = {w.lower() for w in group}
    return index


# 全局索引（模块加载时构建一次）
_SYNONYM_INDEX: dict[str, set[str]] = build_synonym_index()


def expand_synonyms(text: str) -> set[str]:
    """将文本中出现的词汇扩展为同义词集合
    
    扫描文本，对于命中同义词表的词语，返回其所有同义词。
    
    Args:
        text: 输入文本（应为小写）
        
    Returns:
        文本中命中的所有同义词集合
    """
    result: set[str] = set()
    text_lower = text.lower()
    for word, synonyms in _SYNONYM_INDEX.items():
        if word in text_lower:
            result.update(synonyms)
    return result


def get_synonym_group(word: str) -> set[str]:
    """获取某个词的同义词组
    
    Args:
        word: 查询词
        
    Returns:
        同义词组，如果不在同义词表中返回空集
    """
    return _SYNONYM_INDEX.get(word.lower(), set())
